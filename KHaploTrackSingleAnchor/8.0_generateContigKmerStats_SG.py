## This script counts the number of for each smaple_kmerfilt contig generated that are MRD kmers and that are unique i.e not part of the CS kmers
## There is then a csv file that stores the statistics for each contig per reference
## Additionally for each contig file, the unique kmers are converted into a fasta sequence with the appropriate header.
## this will then be used to screen for presence absence of the kmers in the sequenced accessions


#===========================
### import libraries
#============================

import glob  # help in wild card expansion to find files
import os
import pandas as pd
import argparse


#===========================================================================================================================
## =========== Define functions and arguments to be used for analysis =================
#==================================================================

def parse_arguments():
    parser = argparse.ArgumentParser()
    parser.add_argument('--spades_dir', type=str, help="this is the directory where the contigs generated by spades were stored")
    parser.add_argument('--kmer_filter_list', type=str, help="list of kmer filter used tp separate reads into groups before running spades")
    parser.add_argument('--cultivars', type=str, help="cultivar/sample being processed, here this will be just one, that will used to submit the array array job in th bash script running this script")
    args = parser.parse_args()
    return args

##========= Funtion 1====================
#=============================================

def read_kmers_list(kmer_file):
    """read kmer text file line by line removing any characters, i.e white spaces and end of line characters"""
    with open(kmer_file, "r")as file:
        kmer_list=[line.split("\t")[0] for line in file.readlines()]
    return kmer_list


#===========================================================================================================================
### Main function that generates results with functions =====================================================================================
#===========================================================================================================================

def main():
    args = parse_arguments()

    print("Script is starting...")

    # Print to check arguments are expanded correctly
    print(f"Cultivars: {args.cultivars}")

    #cultivars=[f"{args.cultivars}"] ## add the square barces to make sure its interprated as a string not individual letters
    cultivars=args.cultivars.split(',')
    kmer_filter_list=args.kmer_filter_list.split(',')
    spades_dir=args.spades_dir


    for ref in cultivars:
        # we create this dictionary here so that the file is saved one for every reference
        total_contig_kmers_dic={}
        MDR_nums_dic={}
        no_cs_kmers_dic={}
        
        print(f"Processing of files for {ref} started .....")
        
        # for each reference/cutivar, this is where the kmer files are stored
        kmer_dir = f"{args.spades_dir}/{ref}/contig_kmers"

        # once we have the non-CS kmers to be used for the presence absence are names ina fasta file, they will be stored here
        kmer_fasta_dir = f"{args.spades_dir}/{ref}/kmer_fasta_files"

        os.makedirs(f"{kmer_fasta_dir}", exist_ok=True) # make the directory and catch the warning incase it already exists

        
        for kmer in kmer_filter_list:

            print(f"working on text files for kmer filter {kmer}")

            kmers_MDR_files=glob.glob(f"{kmer_dir}/{ref}-{kmer}*_MDR.txt") # this is file1 in function below
            kmers_nonWGS_files=glob.glob(f"{kmer_dir}/{ref}-{kmer}*_MDR_no_WGS_def_kmers.txt") # this is file2 in function below

            # the number of total kmer, MDR kmer and non-CS kmer files should be same for each kmer filter
            print(f"Number of MDR files: {len(kmers_MDR_files)}")
            print(f"Number of non-WGS files: {len(kmers_nonWGS_files)}")

    # to ensure that we are using the same basename for the three files so that we are counting the corresponding file for each contig
    # we start with just one file name and extrapolate the other two from the base name of the first

            for file1 in kmers_MDR_files:

                ## check that the file exists and is not empty before processing
                if not os.path.isfile(file1) or os.path.getsize(file1) == 0:
                    print(f"{file1} is missing or empty. Skipping...")
                    continue  # Skip to the next iteration if the file is missing or empty

                ## the file with kmers present in the MDR kmers matrix
                # count the number of kmers in the file then store the info in a dictioinary

                contig_ID1 = os.path.basename(file1).replace('_MDR.txt', '') 
                contig_kmers=f"{kmer_dir}/{contig_ID1}.txt"
                total_contig_kmers_dic[contig_ID1]=len(read_kmers_list(f"{contig_kmers}"))
                MDR_nums_dic[contig_ID1]=len(read_kmers_list(file1))

                ## the file with non-WGS kmers
                # the result of glob is usually a list, hence we pick the first element, which is the only on here 
                # then convert/take it as a string
                 ## check that the file exists and is not empty before processing, 
                 # this should allow for the script to continue even when the second file is missing or is empty

                ## get the corresponding second file
                file2=glob.glob(f"{kmer_dir}/{contig_ID1}_MDR_no_WGS_def_kmers.txt")
                file2=str(file2[0])

                if not os.path.isfile(file2) or os.path.getsize(file2) == 0:
                    print(f"corresponding file is missing or empty. Skipping...")
                    contig_ID2=os.path.basename(file2).replace('_MDR_no_WGS_def_kmers.txt', '')
                    #print(f"{contig_ID1}\n{contig_ID2}\n{file2}")
                    no_cs_kmers_dic[contig_ID2]=int(0)
                else:
                    # the result of glob is usually a list, hence we pick the first element, which is the only on here 
                    # then convert/take it as a string
                    file2=glob.glob(f"{kmer_dir}/{contig_ID1}_MDR_no_WGS_def_kmers.txt")
                    file2=str(file2[0])
                    print(f"{file2}")
                    contig_ID2=os.path.basename(file2).replace('_MDR_no_WGS_def_kmers.txt', '')
                    no_cs_kmers_dic[contig_ID2]=len(read_kmers_list(file2))

                #print(f"{file1}\n{file2}")
                    print(f"{contig_ID1}\n{contig_ID2}")

                # read the non-WGS kmers, converting them to fasta sequences named accordingly
                    non_WGS_kmers_list=read_kmers_list(file2)

                    # check if the there are no sequences to write, skip and continue instead of writing empty fasta file
                    if len(non_WGS_kmers_list) == 0:
                        print(f"no kmer sequences to write \n")
                    else:
                        non_WGS_kmers_fasta=f"{kmer_fasta_dir}/{os.path.basename(file2).replace('_MDR_no_WGS_def_kmers.txt', '')}.fasta"
                        with open(f"{non_WGS_kmers_fasta}","w") as fasta_file:
                            for i,kmerseq in enumerate(non_WGS_kmers_list,start=1):
                                # create the header
                                header=f">{contig_ID2}_non-CS_{i}"
                                # Write the header and sequence to the file
                                fasta_file.write(f"{header}\n{kmerseq}\n")


        # Convert MDR_num_dic to a DataFrame
        MDR_num_df = pd.DataFrame(list(MDR_nums_dic.items()), columns=['contig_ID', 'no_of_MDR_kmers'])
       
        # Convert no_cs_kmers_dic to a DataFrame
        no_cs_kmers_df = pd.DataFrame(list(no_cs_kmers_dic.items()), columns=['contig_ID', 'num_of_non_WGS_kmers'])
            
        # Convert no_cs_kmers_dic to a DataFrame
        total_contig_kmers_df= pd.DataFrame(list(total_contig_kmers_dic.items()), columns=['contig_ID', 'total_num_kmers'])

        # Merge DataFrames
        final_df = pd.merge(total_contig_kmers_df, MDR_num_df, on='contig_ID')
        final_df= pd.merge(final_df,no_cs_kmers_df, on='contig_ID', how='outer')

        # generate columns of percentages for the numbers

        final_df['perc_MDR_kmers'] = round((final_df['no_of_MDR_kmers']/final_df['total_num_kmers']) * 100,2)

        final_df['perc_non_WGS_kmers'] = round(((final_df['num_of_non_WGS_kmers']/final_df['total_num_kmers']) * 100),2)

        final_df.to_csv(f"{spades_dir}/{ref}/{ref}_sequence_kmer_stats_counts.csv", index=False)

        print(f"Processing of files for {ref} complete!!")


if __name__ == "__main__":
    main()